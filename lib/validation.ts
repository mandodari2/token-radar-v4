/** The whole validation suite, from the snapshot (+ the board, for the ratio check). */
export function validateSnapshot(snapshot: Snapshot, board: BoardRow[]): ValidationReport {
  // SO-TRV4-053 (audit back end): syarat minimum yang dulu crash TypeError
  // mentah (OLS di bawah 2 titik -> NaN; proofGuard lalu membandingkan "NaN").
  // Gagal keras dengan pesan bernama, sebelum satu byte pun ditulis.
  const points = fitPoints(snapshot);
  if (points.length < 2) {
    throw new SnapshotError(`validasi butuh >= 2 titik traded non-CEX bermcap > 0 untuk fit OLS, dapat ${points.length}`);
  }
  if (board.length === 0) {
    throw new SnapshotError('validasi butuh board berisi >= 1 baris, dapat 0 (tidak ada protokol pre-token yang bisa di-ranking)');
  }
  const lp = logPoints(points);
  const report: ValidationReport = {
    generatedFrom: `snapshot ${snapshot.as_of} (${snapshot.source}), ${points.length} fit points`,
    fit: olsFit(lp.xs, lp.ys),
    blind: blindTest(points),
    loo: looValidation(points),
    walkForward: walkForwardValidation(points),
    walkForward2: walkForwardValidation2(points),
    bands: bandSlopes(points),
    zeroMcap: zeroMcapSlopes(snapshot),
    multivariate: multivariateRegression(snapshot, points),
    lowAblation: lowAblation(snapshot, points),
    gasTable: gasTable(),
    capitalTable: capitalTable(),
    ratioVsFixed: ratioVsFixed(board),
  };
  // Pita dengan < 2 titik memberi slope NaN (0/0) — dulu lolos diam-diam ke
  // validation.json sebagai null, lalu proofGuard crash di fmtId(null).
  for (const b of report.bands) {
    if (!Number.isFinite(b.slope)) {
      throw new SnapshotError(`validasi: pita TVL ${b.label} hanya berisi ${b.n} titik (< 2) — slope tak terdefinisi`);
    }
  }
  for (const z of report.zeroMcap) {
    if (!Number.isFinite(z.slope)) {
      throw new SnapshotError(`validasi: slope zero-mcap floor $${z.floorUsd} tak terdefinisi`);
    }
  }
  if (!report.multivariate.coefficients.every((c) => Number.isFinite(c))) {
    throw new SnapshotError('validasi: koefisien regresi multivariat tak terdefinisi (matriks singular?)');
  }
  return report;
}

/** Indonesian number formatting: 3,38 (comma decimal), 2 decimals default. */
export function fmtId(n: number, decimals = 2): string {
  return n.toLocaleString('id-ID', { minimumFractionDigits: decimals, maximumFractionDigits: decimals });
}
