/** One OLS log-log fit: intercept, slope, R^2, slope standard error. */
export interface OlsFit {
  n: number;
  intercept: number;
  slope: number;
  r2: number;
  seSlope: number;
  /** 95% CI of the slope, t(0.975, df=117) = 1.980 (n = 119). */
  ciSlope95: [number, number];
}

/** 97.5% t-quantile for df = 117 (the 119-point fit). */
const T_CRIT_95_DF117 = 1.98;

/** OLS on log10 x / log10 y. */
export function olsFit(xs: number[], ys: number[]): OlsFit {
  const n = xs.length;
  const mx = xs.reduce((s, x) => s + x, 0) / n;
  const my = ys.reduce((s, y) => s + y, 0) / n;
  let sxy = 0;
  let sxx = 0;
  for (let i = 0; i < n; i++) {
    sxy += (xs[i]! - mx) * (ys[i]! - my);
    sxx += (xs[i]! - mx) * (xs[i]! - mx);
  }
  const slope = sxy / sxx;
  const intercept = my - slope * mx;
  let ssRes = 0;
  let ssTot = 0;
  for (let i = 0; i < n; i++) {
    const r = ys[i]! - (intercept + slope * xs[i]!);
    ssRes += r * r;
    ssTot += (ys[i]! - my) * (ys[i]! - my);
  }
  const r2 = 1 - ssRes / ssTot;
  const seSlope = Math.sqrt(ssRes / (n - 2) / sxx);
  return { n, intercept, slope, r2, seSlope, ciSlope95: [slope - T_CRIT_95_DF117 * seSlope, slope + T_CRIT_95_DF117 * seSlope] };
}

/** Median (average of the two middle values when even). */
export function median(values: number[]): number {
  const v = [...values].sort((a, b) => a - b);
  return (v[Math.floor((v.length - 1) / 2)]! + v[Math.floor(v.length / 2)]!) / 2;
}

/** mulberry32: a tiny deterministic PRNG. Seed 12345 = the Devil's Advocate's documented seed. */
export function mulberry32(seed: number): () => number {
  let a = seed | 0;
  return () => {
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** The 119 fit points: traded non-CEX protocols with mcap > 0, in snapshot order. */
export function fitPoints(snapshot: Snapshot): SnapshotProtocol[] {
  return snapshot.protocols.filter((p) => p.mcap_usd !== null && p.mcap_usd > 0 && p.category !== 'CEX');
}

/** Zero/negative-mcap non-CEX protocols (the 14 floored-fit points: 13 zero + autofinance -1). */
export function zeroMcapPoints(snapshot: Snapshot): SnapshotProtocol[] {
  return snapshot.protocols.filter((p) => p.category !== 'CEX' && p.mcap_usd !== null && p.mcap_usd <= 0);
}

function logPoints(rows: SnapshotProtocol[]): { xs: number[]; ys: number[] } {
  return {
    xs: rows.map((p) => Math.log10(p.tvl_usd)),
    ys: rows.map((p) => Math.log10(p.mcap_usd!)),
  };
}

/** Median |log10 error| as a multiplicative factor, and the share within k×. */
function missSummary(missesDex: number[]): { medianMiss: number; within2xPct: number; within3xPct: number; within5xPct: number } {
  const factors = missesDex.map((d) => 10 ** d);
  const within = (k: number): number => (100 * factors.filter((f) => f <= k).length) / factors.length;
  return { medianMiss: median(factors), within2xPct: within(2), within3xPct: within(3), within5xPct: within(5) };
}

export interface BlindTest {
  protocol: string;
  seed: number;
  splits: number;
  trainN: number;
  testN: number;
  wins: number;
  curveMedianMiss: number;
  flatMedianMiss: number;
  curveWithin2xPct: number;
  curveWithin5xPct: number;
  flatWithin5xPct: number;
}

/** 20x random 70/30 splits, curve refit per split, flat = train-median ratio. */
export function blindTest(points: SnapshotProtocol[], seed = 12345): BlindTest {
  const { xs, ys } = logPoints(points);
  const n = xs.length;
  const trainN = Math.floor(0.7 * n);
  const testN = n - trainN;
  const rand = mulberry32(seed);
  let wins = 0;
  const pooledCurve: number[] = [];
  const pooledFlat: number[] = [];
  for (let s = 0; s < 20; s++) {
    const order = Array.from({ length: n }, (_, i) => i);
    for (let i = n - 1; i > 0; i--) {
      const j = Math.floor(rand() * (i + 1));
      [order[i], order[j]] = [order[j]!, order[i]!];
    }
    const trainIdx = order.slice(0, trainN);
    const testIdx = order.slice(trainN);
    const fit = olsFit(
      trainIdx.map((i) => xs[i]!),
      trainIdx.map((i) => ys[i]!),
    );
    const c = median(trainIdx.map((i) => ys[i]! - xs[i]!));
    const ec = testIdx.map((i) => Math.abs(ys[i]! - (fit.intercept + fit.slope * xs[i]!)));
    const ef = testIdx.map((i) => Math.abs(ys[i]! - xs[i]! - c));
    pooledCurve.push(...ec);
    pooledFlat.push(...ef);
    if (median(ec) < median(ef)) wins++;
  }
  const curve = missSummary(pooledCurve);
  const flat = missSummary(pooledFlat);
  return {
    protocol: '20x random 70/30 splits on the 119 traded non-CEX tokens; OLS curve refit on train, flat = train-median mcap/TVL ratio; win = curve median |err| < flat median |err| on the split test set',
    seed,
    splits: 20,
    trainN,
    testN,
    wins,
    curveMedianMiss: curve.medianMiss,
    flatMedianMiss: flat.medianMiss,
    curveWithin2xPct: curve.within2xPct,
    curveWithin5xPct: curve.within5xPct,
    flatWithin5xPct: flat.within5xPct,
  };
}

export interface MissValidation {
  n: number;
  modelMiss: number;
  flatMiss: number;
  modelWithin3xPct: number;
  flatWithin3xPct: number;
}

/** Leave-one-out: each point predicted from a fit on the other 118. */
export function looValidation(points: SnapshotProtocol[]): MissValidation {
  const { xs, ys } = logPoints(points);
  const mm: number[] = [];
  const fm: number[] = [];
  for (let k = 0; k < xs.length; k++) {
    const xk = xs.filter((_, i) => i !== k);
    const yk = ys.filter((_, i) => i !== k);
    const fit = olsFit(xk, yk);
    mm.push(10 ** Math.abs(ys[k]! - (fit.intercept + fit.slope * xs[k]!)));
    const c = median(yk.map((y, j) => y - xk[j]!));
    fm.push(10 ** Math.abs(ys[k]! - xs[k]! - c));
  }
  const within = (v: number[]): number => (100 * v.filter((f) => f <= 3).length) / v.length;
  return { n: xs.length, modelMiss: median(mm), flatMiss: median(fm), modelWithin3xPct: within(mm), flatWithin3xPct: within(fm) };
}

export interface WalkForward extends MissValidation {
  trainN: number;
  testN: number;
  cutoff: string;
  datedN: number;
  noDateExcluded: number;
  /** Train fraction of the dated points (0.5 = WF pertama, 0.6 = WF kedua). */
  trainFrac: number;
}

/** Walk-forward by listing date: train the oldest fraction of the dated
 * points, test the newest rest. Default 50/50 (the original WF); the
 * second walk-forward (SO-TRV4-056, Blind Judge K2 +1) uses 60/40 — a
 * different split, so the 20/20-style headline does not rest on one split. */
export function walkForwardValidation(points: SnapshotProtocol[], trainFrac = 0.5): WalkForward {
  const dated = points.filter((p) => p.listed_at !== null).sort((a, b) => (a.listed_at! < b.listed_at! ? -1 : 1));
  // SO-TRV4-053 (audit back end): dulu dated < 2 titik crash TypeError mentah
  // di test[0].listed_at — gagal keras dengan pesan yang menyebut syaratnya.
  if (dated.length < 4) {
    throw new SnapshotError(`walk-forward butuh >= 4 titik traded bertanggal (latih >= 2, uji >= 2), dapat ${dated.length}`);
  }
  const cut = Math.floor(dated.length * trainFrac);
  const train = dated.slice(0, cut);
  const test = dated.slice(cut);
  const fit = olsFit(
    train.map((p) => Math.log10(p.tvl_usd)),
    train.map((p) => Math.log10(p.mcap_usd!)),
  );
  const c = median(train.map((p) => Math.log10(p.mcap_usd!) - Math.log10(p.tvl_usd)));
  const mm = test.map((p) => 10 ** Math.abs(Math.log10(p.mcap_usd!) - (fit.intercept + fit.slope * Math.log10(p.tvl_usd))));
  const fm = test.map((p) => 10 ** Math.abs(Math.log10(p.mcap_usd!) - Math.log10(p.tvl_usd) - c));
  const within = (v: number[]): number => (100 * v.filter((f) => f <= 3).length) / v.length;
  return {
    n: test.length,
    modelMiss: median(mm),
    flatMiss: median(fm),
    modelWithin3xPct: within(mm),
    flatWithin3xPct: within(fm),
    trainN: train.length,
    testN: test.length,
    cutoff: test[0]!.listed_at!,
    datedN: dated.length,
    noDateExcluded: points.length - dated.length,
    trainFrac,
  };
}

/** Second walk-forward (SO-TRV4-056, Blind Judge K2 +1): same protocol,
 * different split — train the oldest 60%, test the newest 40%. */
export function walkForwardValidation2(points: SnapshotProtocol[]): WalkForward {
  return walkForwardValidation(points, 0.6);
}

export interface BandSlope {
  label: string;
  loUsd: number;
  hiUsd: number | null;
  n: number;
  slope: number;
}

/** OLS slope per TVL band (the $100 jt–$1 M band is the quoted in-band slope). */
export function bandSlopes(points: SnapshotProtocol[]): BandSlope[] {
  const bands: { label: string; lo: number; hi: number | null }[] = [
    { label: '< $10 jt', lo: 0, hi: 10_000_000 },
    { label: '$10 jt–$100 jt', lo: 10_000_000, hi: 100_000_000 },
    { label: '$100 jt–$1 M', lo: 100_000_000, hi: 1_000_000_000 },
    { label: '>= $1 M', lo: 1_000_000_000, hi: null },
  ];
  return bands.map((b) => {
    const sub = points.filter((p) => p.tvl_usd >= b.lo && (b.hi === null || p.tvl_usd < b.hi));
    const { xs, ys } = logPoints(sub);
    return { label: b.label, loUsd: b.lo, hiUsd: b.hi, n: sub.length, slope: olsFit(xs, ys).slope };
  });
}

export interface ZeroMcapFloor {
  floorUsd: number;
  n: number;
  slope: number;
}

/** OLS slope refit with the zero-mcap points floored (n = 119 + 14 = 133). */
export function zeroMcapSlopes(snapshot: Snapshot): ZeroMcapFloor[] {
  const fit = fitPoints(snapshot);
  const zeros = zeroMcapPoints(snapshot);
  const { xs, ys } = logPoints(fit);
  return [1, 1_000, 100_000, 1_000_000].map((floor) => {
    const X = [...xs, ...zeros.map((p) => Math.log10(p.tvl_usd))];
    const Y = [...ys, ...zeros.map(() => Math.log10(floor))];
    return { floorUsd: floor, n: X.length, slope: olsFit(X, Y).slope };
  });
}

/** Solve A x = b by Gaussian elimination with partial pivoting. */
export function solveLinear(aIn: number[][], bIn: number[]): number[] {
  const n = bIn.length;
  const m = aIn.map((row, i) => [...row, bIn[i]!]);
  for (let col = 0; col < n; col++) {
    let piv = col;
    for (let r = col + 1; r < n; r++) if (Math.abs(m[r]![col]!) > Math.abs(m[piv]![col]!) ) piv = r;
    [m[col], m[piv]] = [m[piv]!, m[col]!];
    const pv = m[col]![col]!;
    for (let j = col; j <= n; j++) m[col]![j]! /= pv;
    for (let r = 0; r < n; r++) {
      if (r === col) continue;
      const f = m[r]![col]!;
      if (f !== 0) for (let j = col; j <= n; j++) m[r]![j]! -= f * m[col]![j]!;
    }
  }
  return m.map((row) => row[n]!);
}

export interface Multivariate {
  /** [const, log10(TVL), change_7d, log10(age+1), n_chains, HIGH, LOW] */
  coefficients: number[];
  n: number;
}

/**
 * 7-parameter OLS log10(mcap) ~ 1 + log10(TVL) + change_7d + log10(age+1) +
 * n_chains + HIGH + LOW. Age unknown -> 365 days, change_7d null -> 0 (the
 * V2 spec that reproduces the consultant's coefficients exactly).
 */
export function multivariateRegression(snapshot: Snapshot, points: SnapshotProtocol[]): Multivariate {
  const LOW = new Set(['Restaking', 'Liquid Staking', 'Onchain Capital Allocator', 'Staking Pool']);
  const HIGH = new Set(['Lending', 'Privacy', 'Canonical Bridge']);
  const rows = points.map((p) => {
    const age = ageDays(snapshot.as_of, p.listed_at) ?? 365;
    return {
      x: [
        1,
        Math.log10(p.tvl_usd),
        p.change_7d ?? 0,
        Math.log10(age + 1),
        p.chains.length,
        HIGH.has(p.category ?? '') ? 1 : 0,
        LOW.has(p.category ?? '') ? 1 : 0,
      ],
      y: Math.log10(p.mcap_usd!),
    };
  });
  const k = 7;
  const xtx: number[][] = Array.from({ length: k }, () => new Array<number>(k).fill(0));
  const xty: number[] = new Array<number>(k).fill(0);
  for (const r of rows) {
    for (let i = 0; i < k; i++) {
      for (let j = 0; j < k; j++) xtx[i]![j]! += r.x[i]! * r.x[j]!;
      xty[i]! += r.x[i]! * r.y;
    }
  }
  return { coefficients: solveLinear(xtx, xty), n: rows.length };
}

export interface LowAblationCutoff {
  cutoff: string;
  trainN: number;
  testN: number;
  withLowDex: number;
  withoutLowDex: number;
  deltaDex: number;
}

export interface LowAblation {
  cutoffs: LowAblationCutoff[];
  pooledDeltaDex: number;
}

/**
 * Layer B old-vs-young at 3 cutoffs: clean2 (curve refit + maturity + LOW) vs
 * the same model with LOW removed. Error = median |log10(mcap) - log10(pred)|.
 */
export function lowAblation(snapshot: Snapshot, points: SnapshotProtocol[]): LowAblation {
  const LOW = new Set(['Restaking', 'Liquid Staking', 'Onchain Capital Allocator', 'Staking Pool']);
  const dated = points.filter((p) => p.listed_at !== null).sort((a, b) => (a.listed_at! < b.listed_at! ? -1 : 1));
  const cutoffs = ['2023-06-01', '2024-01-01', '2024-06-01'];
  const rows: LowAblationCutoff[] = [];
  const pooledWith: number[] = [];
  const pooledWithout: number[] = [];
  for (const cutoff of cutoffs) {
    const train = dated.filter((p) => p.listed_at! < cutoff);
    const test = dated.filter((p) => p.listed_at! >= cutoff);
    const fit = olsFit(
      train.map((p) => Math.log10(p.tvl_usd)),
      train.map((p) => Math.log10(p.mcap_usd!)),
    );
    const predict = (p: SnapshotProtocol, useLow: boolean): number => {
      const s = impliedValue(p, snapshot.as_of, MODEL);
      // Curve refit on train + the snapshot's own maturity/LOW (not the
      // full-sample MODEL constants): rebuild from the refit curve.
      const base = 10 ** (fit.intercept + fit.slope * Math.log10(p.tvl_usd));
      const low = useLow && LOW.has(p.category ?? '') ? MODEL.category_low_multiplier : 1;
      return Math.log10(Math.max(1, base * s.maturityMult * low));
    };
    const withLow = test.map((p) => Math.abs(Math.log10(p.mcap_usd!) - predict(p, true)));
    const withoutLow = test.map((p) => Math.abs(Math.log10(p.mcap_usd!) - predict(p, false)));
    pooledWith.push(...withLow);
    pooledWithout.push(...withoutLow);
    rows.push({
      cutoff,
      trainN: train.length,
      testN: test.length,
      withLowDex: median(withLow),
      withoutLowDex: median(withoutLow),
      deltaDex: median(withoutLow) - median(withLow),
    });
  }
  return { cutoffs: rows, pooledDeltaDex: median(pooledWithout) - median(pooledWith) };
}

