// Build-time validation of the K1/clean2 curve (SO-TRV4-045).
//
// Every validation number the dashboard and the dossier show is computed HERE,
// from the sealed snapshot the build reads — never typed by hand. The module is
// pure and deterministic: no I/O, no clock, no Math.random. The only randomness
// is a seeded PRNG (mulberry32, seed 12345 — the Devil's Advocate's documented
// seed) for the blind test, so a rebuild reproduces the numbers bit-for-bit.
//
// What it computes (protocol per item — the definition IS the code):
// - fit: full-sample OLS log10(mcap) = a + b*log10(TVL) on the 119 traded
//   non-CEX protocols with mcap > 0, with R^2 and the 95% CI of the slope.
// - blind: 20x random 70/30 splits (train 83 / test 36, seed 12345). Per split
//   the OLS curve is refit on train only; the flat baseline is the train-median
//   log10(mcap/TVL) ratio (MODEL_RESEARCH_V2.md §3.3 — the surviving protocol
//   spec; SPEC_V2 §4.2 calls it "rasio tetap 0,20", the radar-2 legacy label).
//   Win = curve median |error| < flat median |error| on that split's test set.
//   Typical errors are pooled medians over all 20x36 test predictions.
// - loo: leave-one-out (each point predicted from a fit on the other 118).
// - walkForward: by listing date — train the oldest half of the 87 dated
//   points, test the newest half; the 32 points without listed_at are excluded
//   (stated, not hidden). Same definitions as rnd/loo_walkforward.py.
// - walkForward2 (SO-TRV4-056): the same protocol with a different split —
//   train the oldest 60%, test the newest 40% — so the validation headline
//   does not rest on a single split.
// - bands: OLS slope per TVL band; the $100 jt–$1 M band is the "in-band
//   slope" the modal quotes (n=16 there, so it is fragile — the report says so).
// - zeroMcap: OLS slope refit on 119 + the 14 zero/negative-mcap non-CEX
//   protocols (incl. autofinance mcap -1) floored at $1 / $1.000 / $100.000 /
//   $1 jt (n=133). This reproduces the research table (MODEL_RESEARCH_V2 §3.3);
//   the Devil's Advocate's 0,560 / 0,459 do NOT reproduce from any sample
//   variant tried — see REPRODUCIBILITY_REPORT.md.
// - multivariate: 7-parameter OLS log10(mcap) ~ 1 + log10(TVL) + change_7d +
//   log10(age+1) + n_chains + HIGH + LOW, with age null -> 365 days and
//   change_7d null -> 0. Reproduces the consultant's coefficients exactly
//   (V3_CONSULTANT_REPORT.md §3: HIGH -0,089, LOW -0,703).
// - lowAblation: Layer B old-vs-young at 3 cutoffs — clean2 (curve refit +
//   maturity + LOW) vs the same model with LOW removed. Median |error| dex.
// - gasTable / capitalTable: the modal's gas + capital tiers, generated by
//   calling the SAME gasUsd / capitalFor functions lib/model.ts uses to price
//   every board row (single source of truth, not a retyped table).
// - ratioVsFixed: the honest replacement for the modal's "~8x" sentence — the
//   0.20*TVL-vs-implied ratio at the board's #1 row AND the median board row.
//   (The old sentence was only true for giant TVLs; the median board row's
//   implied value is LARGER than 0.20*TVL.)
//
// What it does NOT compute (R&D history, honestly labelled in the UI):
// - the ~0,51 dex error floor (best Layer A median error across 20+ model
//   families — needs the whole Layer A harness, rnd/spike_models.py et al.);
// - the Layer B +0,19..+1,72 dex range for floored fits (Tier-1 experiments,
//   V3_EXPERIMENTS_TIER1_REPORT.md §4.2 — the harness script was not preserved).
// Both are quoted in the UI/dossier WITH their provenance, not as build output.

