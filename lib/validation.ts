export interface RatioVsFixed {
  top1Slug: string;
  top1TvlUsd: number;
  top1ImpliedUsd: number;
  top1Fixed020Usd: number;
  top1Ratio: number;
  medianBoardRatio: number;
}

/** 0.20*TVL vs implied: at the board's #1 row and the median board row. */
export function ratioVsFixed(board: BoardRow[]): RatioVsFixed {
  // SO-TRV4-053 (audit back end): dulu board kosong crash TypeError mentah di
  // board[0].slug — gagal keras dengan pesan yang menyebut syaratnya.
  if (board.length === 0) {
    throw new SnapshotError('ratioVsFixed butuh board berisi >= 1 baris, dapat 0 (tidak ada protokol pre-token yang bisa di-ranking)');
  }
  const top = board[0]!;
  const ratios = board.map((r) => (0.2 * r.tvl_usd) / r.implied_value_usd);
  return {
    top1Slug: top.slug,
    top1TvlUsd: top.tvl_usd,
    top1ImpliedUsd: top.implied_value_usd,
    top1Fixed020Usd: 0.2 * top.tvl_usd,
    top1Ratio: (0.2 * top.tvl_usd) / top.implied_value_usd,
    medianBoardRatio: median(ratios),
  };
}

